const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'../../..');
const out=path.resolve(__dirname,'../source');
fs.mkdirSync(out,{recursive:true});
const original=fs.readFileSync(path.join(root,'마법학교_최초기획안.html'),'utf8');
const body=original.match(/<main[^>]*>([\s\S]*?)<\/main>/)[1];
const images=[...body.matchAll(/<img\b[^>]*src="data:image\/png;base64,([^"]+)"[^>]*>/g)];
const clean=body.replace(/<img\b[^>]*>/g,'[화면 이미지 별도 확인]').replace(/<script\b[\s\S]*?<\/script>/g,'');
const text=clean.replace(/<\/(?:p|h[1-6]|tr|li|figcaption|div|aside|section)>/g,'\n').replace(/<[^>]*>/g,' ').replace(/&amp;/g,'&').replace(/&lt;/g,'<').replace(/&gt;/g,'>').replace(/&quot;/g,'"').replace(/[ \t]+/g,' ').split('\n').map(x=>x.trim()).filter(Boolean).join('\n');
fs.writeFileSync(path.join(out,'original-body.html'),clean);
fs.writeFileSync(path.join(out,'original-text.txt'),text);
const manifest=JSON.parse(fs.readFileSync(path.join(root,'screens/manifest.json')));
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const imageIds=[...body.matchAll(/<figure class="game-figure" id="screen-([^"]+)"/g)].map(m=>m[1]);
const report={htmlSha256:hash(original),lines:text.split('\n').length,characters:text.length,headings:[...body.matchAll(/<h2[^>]*>(.*?)<\/h2>/g)].map(x=>x[1]),screens:images.map((m,i)=>({id:imageIds[i],embeddedHash:hash(Buffer.from(m[1],'base64')),fileHash:hash(fs.readFileSync(path.join(root,'screens',imageIds[i]+'.png')))}))};
fs.writeFileSync(path.join(out,'extraction-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({...report,screens:report.screens.map(s=>({id:s.id,match:s.embeddedHash===s.fileHash}))},null,2));
